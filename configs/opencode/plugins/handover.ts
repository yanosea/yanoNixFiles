// handover.ts - drop a placeholder HANDOVER.md before compaction.
// Same placeholder contract as configs/agents/hooks/generate-handover.sh.
import { copyFile, readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"

const MARKER = "# Auto-generated note"

const pad = (n: number) => String(n).padStart(2, "0")

export const HandoverPlugin = async ({ directory }: { directory: string }) => ({
  "experimental.session.compacting": async (input: { sessionID: string }) => {
    const file = join(directory, "HANDOVER.md")
    const current = await readFile(file, "utf8").catch(() => undefined)
    // don't clobber a real handover (written by the handover skill or by hand);
    // only the placeholder itself is safe to overwrite
    if (current !== undefined) {
      if (current.split("\n", 1)[0] !== MARKER) return
      await copyFile(file, `${file}.bak`)
    }
    const d = new Date()
    const timestamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`
    await writeFile(
      file,
      `${MARKER}

- Generated at: ${timestamp}
- Trigger: compaction
- Session: ${input.sessionID ?? "unknown"}
- This file was auto-generated by the session.compacting hook
- Run the \`handover\` skill to generate a detailed handover note

## Notice

- This is a snapshot taken just before context compaction
- Review this file at the start of the next session
`,
    )
  },
})
